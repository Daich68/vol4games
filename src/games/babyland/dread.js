/* BABYLAND — нарастание хоррора и давление времени.
 *
 * Бриф Ланы, стр. 12: «Важно, чтобы хоррор возникал ПОСТЕПЕННО и не разрушал
 * ощущение "милой игры" с первых секунд». Значит хоррор — не событие, а
 * шкала, и она должна ехать сама, а не только по кликам игрока.
 *
 * Две вещи, которых не было:
 *
 * 1. ДАВЛЕНИЕ. Раньше цикл реакций двигался только на новом клике по
 *    неправильной вещи. Слотов шесть, поэтому одеть её неправильно и
 *    остановиться означало, что игра ждёт вечно: проиграть было нельзя.
 *    По брифу (стр. 7) «Уродка» наступает за то, что игрок ДЕРЖИТ её
 *    некрасивой в течение трёх-четырёх повторений цикла. Значит считать
 *    надо состояние, а не клики: пока на ней есть неправильное, машине
 *    невыносимо, и она сама доводит реакцию до следующего уровня.
 *
 * 2. ДЕГРАДАЦИЯ РАБОЧЕГО СТОЛА. Игра идёт в окнах, и портиться должны
 *    окна. Заголовки окон-спутников — это требования к девочке словами
 *    самой Ланы; по мере нарастания они превращаются из инструкций в
 *    требования, потом в одно слово. Адреса начинают ветвиться: её
 *    копируют. Это дешевле и страшнее любого скримера, потому что
 *    происходит на периферии зрения.
 */

// Пока на ней есть неправильное, уровень сам растёт раз в столько.
// 9 секунд: достаточно, чтобы успеть переодеть, и мало, чтобы забыть.
export const PRESSURE_MS = 9000;

/* Заголовки окон-спутников по ступеням. Всё — строки Ланы:
   ступень 0 — инструкции из makeup.txt («так что требуется: …»),
   ступень 1 — из hair.txt, где инструкция становится насилием,
   ступень 2 — «лишь бы любили», причина всего,
   ступень 3 — системная фраза игры,
   ступень 4 — от девочки остаётся местоимение. */
const TITLES = [
  ['укладывать брови', 'казаться меньше', 'подводить линию роста', 'рисовать солнечный свет'],
  ['укладывать брови', 'казаться меньше', 'кожу сорви, натри до блеска', 'рисовать солнечный свет'],
  ['лишь бы любили', 'казаться меньше', 'кожу сорви, натри до блеска', 'лишь бы любили'],
  ['эта девочка хочет быть красивой', 'лишь бы любили',
   'эта девочка хочет быть красивой', 'кожу сорви, натри до блеска'],
  ['она', 'она', 'она', 'она'],
];

// Адрес ветвится: на ступени N она уже не одна, её копируют.
const ADDRESS = (level) =>
  level < 2 ? 'http://127.0.0.1:5173/babyland/girl.html'
            : `http://127.0.0.1:5173/babyland/girl_${level + 1}.html`;

export function createDread(root) {
  const frames = [...root.querySelectorAll('.fragment')];
  const gaze = root.querySelector('#win-gaze');
  let level = 0;

  function paint() {
    const step = Math.min(level, TITLES.length - 1);
    root.dataset.dread = String(step);
    TITLES[step].forEach((text, i) => {
      const bar = frames[i]?.querySelector('b');
      if (bar) bar.textContent = text;
    });
    // окна-спутники проступают по одному, а не все сразу: на нулевой
    // ступени их два, дальше открываются остальные — «милая игра» не
    // должна быть разрушена с первых секунд
    frames.forEach((frame, i) => { frame.hidden = i >= Math.min(2 + step, frames.length); });
    const url = gaze?.querySelector('.url');
    if (url) url.textContent = ADDRESS(step);
  }

  return {
    set(next) { if (next === level) return; level = Math.max(0, next); paint(); },
    get() { return level; },
    reset() { level = 0; paint(); },
    paint,
  };
}
